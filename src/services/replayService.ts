const SEEDED_REPLAYS: MatchReplayData[] = [
  REPLAY_M9945_BEAD16,
  REPLAY_M7712_WHOT,
  REPLAY_M7709_LUDO_BLITZ,
  REPLAY_M7702_DRAUGHTS,
  REPLAY_M7695_LUDO_CLASSIC,
];

export const getStoredReplays = (): MatchReplayData[] => {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_REPLAYS);
    if (!raw) return SEEDED_REPLAYS;
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : SEEDED_REPLAYS;
  } catch {
    return SEEDED_REPLAYS;
  }
};

export const saveReplay = (replay: MatchReplayData) => {
  try {
    const existing = getStoredReplays();
    const updated = [replay, ...existing.filter((r) => r.id !== replay.id)];
    localStorage.setItem(STORAGE_KEY_REPLAYS, JSON.stringify(updated));
  } catch {
    // ignore
  }
};

export const getReplayById = (matchId: string): MatchReplayData | undefined => {
  const all = getStoredReplays();
  return all.find((r) => r.id === matchId || r.roomCode.includes(matchId));
};

